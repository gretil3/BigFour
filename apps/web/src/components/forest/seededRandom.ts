/**
 * Seeded PRNG (mulberry32), so anything decorative that looks random renders the
 * same on every load. Ported from David's portfolio (website_portofolio/src/lib).
 */
export function mulberry32(seed: number) {
  let a = seed;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
